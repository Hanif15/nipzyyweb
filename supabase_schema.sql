-- Query SQL untuk membuat tabel short_links di Supabase
-- Buka dashboard Supabase -> SQL Editor -> Tempel query ini lalu klik RUN

create table if not exists public.short_links (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  original_url text not null,
  clicks integer default 0,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Index pada kolom slug untuk lookup instan
create index if not exists idx_short_links_slug on public.short_links(slug);

-- Izinkan akses publik (Row Level Security / RLS)
alter table public.short_links enable row level security;

-- Policy untuk membaca link
create policy "Allow public read access"
  on public.short_links
  for select
  using (true);

-- Policy untuk menambahkan link baru
create policy "Allow public insert"
  on public.short_links
  for insert
  with check (true);

-- Policy untuk update counter klik
create policy "Allow public update clicks"
  on public.short_links
  for update
  using (true);

-- Policy untuk menghapus link
create policy "Allow public delete"
  on public.short_links
  for delete
  using (true);
